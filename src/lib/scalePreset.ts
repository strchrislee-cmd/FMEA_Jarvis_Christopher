import type { ScaleTable } from '../types/fmea'

// 회사 S/O/D 기준표(S&PS DFMEA Risk Numbering)의 DFMEA 기본값 프리셋.
// 하드코딩 상수가 아니라 "되돌릴 수 있는 기본값"으로 취급 — 사용자는 척도표 편집에서 계속 수정 가능.
// 정의된 등급(10/8/6/4/1)만 채우고, 중간값(9/7/5/3/2)은 빈칸. (D는 Design Control 기준이라 DFMEA 전용)
// 배열 index i = 등급 (i+1). 예: 등급 10 → index 9.

// DFMEA 하단 Note(비기능 성능 정의) — 척도표 화면 각주로만 표시(편집 대상 아님).
export const DFMEA_SCALE_NOTE =
  '비기능(Non-functional) 성능 = HUE/인간공학, 원가, DFM/DFT, 일정 등을 포함한다.'

export function dfmeaScalePreset(): ScaleTable {
  // 등급→문구 맵을 index 배열로 전개 (정의 안 된 등급은 '')
  const build = (byGrade: Record<number, string>): string[] =>
    Array.from({ length: 10 }, (_, i) => byGrade[i + 1] ?? '')

  const S = build({
    10: '안전/법규 관련 고장. 경고 없이 발생할 수 있음 (신뢰성: 시스템 전체 교체가 필요한 치명적 고장)',
    8: '주요 기능 또는 핵심 비기능 성능의 상실·저하 (신뢰성: 제품 고장, 평균수리시간 1개월 미만)',
    6: '부차 기능 또는 비기능 성능의 상실·저하 (신뢰성: 처리량 저하를 유발하는 고장)',
    4: '기능/비기능 성능 저하로 인한 불편. 툴 리셋이나 재보정이 필요한 수준',
    1: '영향 없음. 시스템 성능에 영향을 주지 않는 고장',
  })

  const O = build({
    10: '매우 높음, 발생 확률 상시 (매일/매시간 만성적 발생)',
    8: '높음, 10%≤O<20% (가동 1개월 내 발생 가능)',
    6: '보통, 5%≤O<10% (가동 1년 내 발생 가능)',
    4: '낮음, 1%≤O<5% (시스템 수명 기간 중 발생 가능)',
    1: '매우 낮음, <1% (시스템 수명 중 발생 가능성 희박)',
  })

  const D = build({
    10: '발생 전 검출 능력 없음, 발생 후에도 검출 거의 불가',
    8: '발생 전 검출은 불가하나 발생 후 일부 검출 가능',
    6: '발생 후 검출하는 공식 단계는 있으나 발생 지점보다 하류 (발생 후 검출)',
    4: '발생 지점에서 검출하는 공식 단계(예: 검사) 있음 (발생 시점 검출)',
    1: '예방을 위한 공식 절차 있음, 표준시험절차 문서화 필요 (발생 전 검출)',
  })

  return { S, O, D }
}
